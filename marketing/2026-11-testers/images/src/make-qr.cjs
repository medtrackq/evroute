// node make-qr.cjs  → qr-data.js (used by card.js) + qr-card-station.svg (vector, for anyone who needs the bare QR)
// needs npm "qrcode" (any folder: NODE_PATH=/path/to/node_modules node make-qr.cjs)
// QR rules (brief 24 พ.ย.): vector · error correction Q · quiet zone 4 modules · dark on white · no logo in the middle
const fs = require('fs'), path = require('path');
const QR = require('qrcode');
const TEXT = 'https://evroute.info/?ref=card-station';
const EC = 'Q', QUIET = 4;
const q = QR.create(TEXT, { errorCorrectionLevel: EC });
const n = q.modules.size, bits = q.modules.data;
let d = '';
for (let y = 0; y < n; y++) {
  for (let x = 0; x < n; x++) {
    if (!bits[y * n + x]) continue;
    let run = 1; while (x + run < n && bits[y * n + x + run]) run++;
    d += `M${x + QUIET} ${y + QUIET}h${run}v1h-${run}z`;
    x += run - 1;
  }
}
const total = n + QUIET * 2;
fs.writeFileSync(path.join(__dirname, 'qr-data.js'),
  `// generated by make-qr.cjs — do not edit\nwindow.EVQR = ${JSON.stringify({ text: TEXT, ec: EC, version: q.version, modules: n, quiet: QUIET, total, d })};\n`);
fs.writeFileSync(path.join(__dirname, 'qr-card-station.svg'),
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${total} ${total}" shape-rendering="crispEdges"><rect width="${total}" height="${total}" fill="#fff"/><path fill="#121826" d="${d}"/></svg>\n`);
console.log(`QR ${TEXT} · EC ${EC} · version ${q.version} · ${n}×${n} modules + quiet ${QUIET} = ${total}`);
